CREATE OR REPLACE FUNCTION app_private.resumo_prestacao_v108(
 p_empresa_id uuid,p_entregador_id uuid,p_data date
) RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path TO ''
AS $$
DECLARE
 v_inicio timestamptz;
 v_fim timestamptz;
 v_res jsonb;
BEGIN
 IF p_data IS NULL THEN RAISE EXCEPTION 'Data obrigatória.'; END IF;
 IF p_data > (now() AT TIME ZONE 'America/Fortaleza')::date THEN
  RAISE EXCEPTION 'Data futura não permitida.';
 END IF;
 v_inicio := (p_data::timestamp AT TIME ZONE 'America/Fortaleza');
 v_fim := ((p_data+1)::timestamp AT TIME ZONE 'America/Fortaleza');
 WITH movimentos AS (
   SELECT vr.forma_pagamento forma,vr.destino_recebimento_v108 destino,
     vr.valor::numeric valor
   FROM public.venda_recebimentos vr
   WHERE vr.empresa_id=p_empresa_id AND vr.recebido_por=p_entregador_id
     AND vr.created_at>=v_inicio AND vr.created_at<v_fim
   UNION ALL
   SELECT pa.forma_pagamento,pa.destino_recebimento_v108,pa.valor
   FROM public.pagamentos pa
   WHERE pa.empresa_id=p_empresa_id AND pa.recebido_por=p_entregador_id
     AND pa.created_at>=v_inicio AND pa.created_at<v_fim
   UNION ALL
   SELECT fe.forma_pagamento,CASE
     WHEN fe.forma_pagamento='DINHEIRO' THEN 'ENTREGADOR'
     ELSE COALESCE(
       (SELECT pa.destino_recebimento_v108 FROM public.pagamentos pa
         WHERE pa.id=fe.origem_id AND fe.tipo_origem='PAGAMENTO_PARCELA'
           AND pa.empresa_id=fe.empresa_id),
       (SELECT pa.destino_recebimento_v108 FROM public.pagamentos pa
         JOIN public.recebimentos_cliente rc ON rc.id=pa.recebimento_id
         WHERE fe.tipo_origem='RECEBIMENTO_CLIENTE' AND rc.id=fe.origem_id
           AND pa.empresa_id=fe.empresa_id ORDER BY pa.id LIMIT 1)
     ) END,
     -fe.valor
   FROM public.financeiro_estornos fe
   WHERE fe.empresa_id=p_empresa_id AND fe.recebido_por_original=p_entregador_id
     AND fe.origem_created_at>=v_inicio AND fe.origem_created_at<v_fim
 )
 SELECT jsonb_build_object(
   'dinheiro',coalesce(sum(valor) FILTER (WHERE forma='DINHEIRO'),0),
   'pix_empresa',coalesce(sum(valor) FILTER (WHERE forma='PIX' AND destino='EMPRESA'),0),
   'pix_entregador',coalesce(sum(valor) FILTER (WHERE forma='PIX' AND destino='ENTREGADOR'),0),
   'cartao_empresa',coalesce(sum(valor) FILTER (WHERE forma='CARTAO' AND destino='EMPRESA'),0),
   'cartao_entregador',coalesce(sum(valor) FILTER (WHERE forma='CARTAO' AND destino='ENTREGADOR'),0),
   'sem_classificacao',coalesce(sum(abs(valor)) FILTER (WHERE
        (forma<>'DINHEIRO' AND destino IS NULL) OR forma IN ('TRANSFERENCIA','OUTRO')),0),
   'total_recebido',coalesce(sum(valor),0),
   'quantidade_movimentos',count(*)
 ) INTO v_res FROM movimentos;
 RETURN v_res;
END;
$$;

CREATE OR REPLACE FUNCTION public.resumo_prestacao_v108(
 p_empresa_id uuid,p_data date,p_entregador_id uuid DEFAULT NULL
) RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path TO ''
AS $$
DECLARE v_uid uuid := auth.uid();v_entregador uuid:=coalesce(p_entregador_id,auth.uid());
BEGIN
 IF v_uid IS NULL OR NOT app_private.is_empresa_member(p_empresa_id) THEN
  RAISE EXCEPTION 'Sessão/empresa inválida.';
 END IF;
 IF v_entregador<>v_uid AND NOT app_private.has_permission(p_empresa_id,'FINANCEIRO_AUDITAR') THEN
  RAISE EXCEPTION 'Sem permissão para consultar outro entregador.';
 END IF;
 RETURN app_private.resumo_prestacao_v108(p_empresa_id,v_entregador,p_data);
END;
$$;

CREATE OR REPLACE FUNCTION public.configurar_destinos_v108(
 p_empresa_id uuid,p_pix text,p_cartao text
) RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path TO ''
AS $$
DECLARE v_uid uuid:=auth.uid();
BEGIN
 IF v_uid IS NULL OR NOT app_private.is_empresa_member(p_empresa_id)
    OR NOT app_private.has_permission(p_empresa_id,'EMPRESA_CONFIGURAR') THEN
  RAISE EXCEPTION 'Somente gestão da empresa pode alterar destinatários.';
 END IF;
 IF p_pix NOT IN ('EMPRESA','ENTREGADOR') OR p_cartao NOT IN ('EMPRESA','ENTREGADOR') THEN
   RAISE EXCEPTION 'Destino inválido.';
 END IF;
 UPDATE public.empresa_configuracoes
   SET destino_pix_v108=p_pix,destino_cartao_v108=p_cartao,updated_at=now()
   WHERE empresa_id=p_empresa_id;
 IF NOT FOUND THEN RAISE EXCEPTION 'Empresa sem configurações.'; END IF;
 INSERT INTO public.auditoria_eventos(empresa_id,usuario_id,entidade,entidade_id,acao,dados)
 VALUES(p_empresa_id,v_uid,'CONFIGURACAO',p_empresa_id::text,
  'RECEBIMENTOS_DESTINATARIOS_ALTERADOS_V108',
  jsonb_build_object('pix',p_pix,'cartao',p_cartao));
 RETURN jsonb_build_object('pix',p_pix,'cartao',p_cartao);
END;
$$;

CREATE OR REPLACE FUNCTION public.enviar_prestacao_v108(
 p_empresa_id uuid,p_data date,
 p_dinheiro numeric,p_pix numeric,p_cartao numeric,
 p_comprovante_pix text DEFAULT NULL,p_comprovante_cartao text DEFAULT NULL,
 p_observacao text DEFAULT NULL
) RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path TO ''
AS $$
DECLARE v_uid uuid:=auth.uid();v_res jsonb;v_prestacao public.prestacoes_contas_v108%rowtype;
  v_pix_esperado numeric;v_cartao_esperado numeric;v_dinheiro_esperado numeric;
BEGIN
 IF v_uid IS NULL OR NOT app_private.is_empresa_member(p_empresa_id)
   OR NOT app_private.has_permission(p_empresa_id,'PAGAMENTO_REGISTRAR') THEN
  RAISE EXCEPTION 'Sem permissão para prestar contas.';
 END IF;
 IF p_data IS NULL OR p_data>(now() AT TIME ZONE 'America/Fortaleza')::date
   OR p_data<(now() AT TIME ZONE 'America/Fortaleza')::date-90 THEN
  RAISE EXCEPTION 'Data fora do período permitido (últimos 90 dias).';
 END IF;
 IF p_dinheiro IS NULL OR p_pix IS NULL OR p_cartao IS NULL OR
    p_dinheiro<0 OR p_pix<0 OR p_cartao<0 OR
    p_dinheiro>100000000 OR p_pix>100000000 OR p_cartao>100000000 THEN
  RAISE EXCEPTION 'Valores declarados inválidos.';
 END IF;
 IF length(coalesce(p_observacao,''))>1500 OR
    length(coalesce(p_comprovante_pix,''))>250 OR
    length(coalesce(p_comprovante_cartao,''))>250 THEN
  RAISE EXCEPTION 'Observação ou referência de comprovante muito longa.';
 END IF;
 PERFORM pg_advisory_xact_lock(
   hashtextextended('prestacao-v108:'||p_empresa_id::text||':'||v_uid::text||':'||p_data::text,0)
 );
 v_res:=app_private.resumo_prestacao_v108(p_empresa_id,v_uid,p_data);
 IF (v_res->>'sem_classificacao')::numeric<>0 THEN
  RAISE EXCEPTION 'Há recebimentos sem destinatário identificado. Solicite classificação ao Financeiro.';
 END IF;
 v_pix_esperado := (v_res->>'pix_entregador')::numeric;
 v_cartao_esperado := (v_res->>'cartao_entregador')::numeric;
 v_dinheiro_esperado := (v_res->>'dinheiro')::numeric;
 IF p_pix>v_pix_esperado OR p_cartao>v_cartao_esperado OR p_dinheiro>v_dinheiro_esperado THEN
  RAISE EXCEPTION 'Valor declarado maior que o valor sob responsabilidade do entregador.';
 END IF;
 IF p_pix>0 AND coalesce(trim(p_comprovante_pix),'')='' THEN
  RAISE EXCEPTION 'Informe a referência do comprovante de repasse PIX.';
 END IF;
 IF p_cartao>0 AND coalesce(trim(p_comprovante_cartao),'')='' THEN
  RAISE EXCEPTION 'Informe a referência do repasse do cartão.';
 END IF;
 SELECT * INTO v_prestacao FROM public.prestacoes_contas_v108 p
 WHERE p.empresa_id=p_empresa_id AND p.entregador_id=v_uid
  AND p.data_referencia=p_data FOR UPDATE;
 IF v_prestacao.id IS NOT NULL AND v_prestacao.status IN ('CONFERIDA','COM_DIVERGENCIA') THEN
  RAISE EXCEPTION 'Prestação conferida pelo CD: bloqueada para edição.';
 END IF;
 INSERT INTO public.prestacoes_contas_v108(
  empresa_id,entregador_id,data_referencia,status,valores_esperados,
  dinheiro_declarado,pix_repassado,cartao_repassado,
  comprovante_pix,comprovante_cartao,observacao_entregador,enviado_at,updated_at
 ) VALUES (
  p_empresa_id,v_uid,p_data,'ENVIADA',v_res,round(p_dinheiro,2),round(p_pix,2),
  round(p_cartao,2),nullif(trim(p_comprovante_pix),''),
  nullif(trim(p_comprovante_cartao),''),nullif(trim(p_observacao),''),now(),now()
 )
 ON CONFLICT (empresa_id,entregador_id,data_referencia) DO UPDATE SET
   status='ENVIADA',valores_esperados=EXCLUDED.valores_esperados,
   dinheiro_declarado=EXCLUDED.dinheiro_declarado,pix_repassado=EXCLUDED.pix_repassado,
   cartao_repassado=EXCLUDED.cartao_repassado,comprovante_pix=EXCLUDED.comprovante_pix,
   comprovante_cartao=EXCLUDED.comprovante_cartao,
   observacao_entregador=EXCLUDED.observacao_entregador,
   enviado_at=now(),updated_at=now(),observacao_cd=NULL,
   conferido_por=NULL,conferido_at=NULL
 RETURNING * INTO v_prestacao;
 INSERT INTO public.auditoria_eventos(empresa_id,usuario_id,entidade,entidade_id,acao,dados)
 VALUES(p_empresa_id,v_uid,'PRESTACAO',v_prestacao.id::text,'PRESTACAO_ENVIADA_V108',
  jsonb_build_object('data',p_data,'esperado',v_res,'dinheiro',p_dinheiro,'pix',p_pix,'cartao',p_cartao));
 RETURN jsonb_build_object('id',v_prestacao.id,'status',v_prestacao.status);
END;
$$;

CREATE OR REPLACE FUNCTION public.conferir_prestacao_v108(
 p_empresa_id uuid,p_id bigint,p_dinheiro numeric,p_pix numeric,p_cartao numeric,
 p_taxa_cartao numeric DEFAULT 0,p_observacao text DEFAULT NULL,
 p_devolver boolean DEFAULT false
) RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path TO ''
AS $$
DECLARE v_uid uuid:=auth.uid();v_p public.prestacoes_contas_v108%rowtype;
  v_res jsonb;v_div numeric;v_esperado_cartao numeric;v_status text;
BEGIN
 IF v_uid IS NULL OR NOT app_private.is_empresa_member(p_empresa_id) OR
  NOT app_private.has_permission(p_empresa_id,'FINANCEIRO_AUDITAR') THEN
  RAISE EXCEPTION 'Sem permissão para conferir prestação.';
 END IF;
 IF p_dinheiro IS NULL OR p_pix IS NULL OR p_cartao IS NULL OR p_taxa_cartao IS NULL
 OR p_dinheiro<0 OR p_pix<0 OR p_cartao<0 OR p_taxa_cartao<0 THEN
  RAISE EXCEPTION 'Conferência com valores inválidos.';
 END IF;
 IF length(coalesce(p_observacao,''))>1500 THEN RAISE EXCEPTION 'Observação muito longa.';END IF;
 SELECT * INTO v_p FROM public.prestacoes_contas_v108 p
 WHERE p.empresa_id=p_empresa_id AND p.id=p_id FOR UPDATE;
 IF v_p.id IS NULL OR v_p.status NOT IN ('ENVIADA','DEVOLVIDA') THEN
  RAISE EXCEPTION 'Prestação inexistente, já conferida ou bloqueada.';
 END IF;
 IF p_devolver AND length(trim(coalesce(p_observacao,'')))<8 THEN
   RAISE EXCEPTION 'Informe motivo para devolver ao entregador.';
 END IF;
 -- Se houve nova venda ou estorno após envio, exige nova prestação.
 v_res:=app_private.resumo_prestacao_v108(p_empresa_id,v_p.entregador_id,v_p.data_referencia);
 IF v_res<>v_p.valores_esperados THEN
  RAISE EXCEPTION 'Há movimentações novas no período. Solicite reenvio antes de conferir.';
 END IF;
 v_esperado_cartao:= (v_res->>'cartao_entregador')::numeric - p_taxa_cartao;
 IF v_esperado_cartao<0 THEN RAISE EXCEPTION 'Taxa acima do cartão esperado.';END IF;
 v_div:=abs(p_dinheiro - (v_res->>'dinheiro')::numeric)
      +abs(p_pix - (v_res->>'pix_entregador')::numeric)
      +abs(p_cartao - v_esperado_cartao);
 v_status:=CASE WHEN p_devolver THEN 'DEVOLVIDA'
   WHEN v_div<=0.009 THEN 'CONFERIDA'
   ELSE 'COM_DIVERGENCIA' END;
 UPDATE public.prestacoes_contas_v108
 SET status=v_status,
   dinheiro_conferido=CASE WHEN p_devolver THEN NULL ELSE round(p_dinheiro,2) END,
   pix_conferido=CASE WHEN p_devolver THEN NULL ELSE round(p_pix,2) END,
   cartao_conferido=CASE WHEN p_devolver THEN NULL ELSE round(p_cartao,2) END,
   taxa_cartao_autorizada=CASE WHEN p_devolver THEN 0 ELSE round(p_taxa_cartao,2) END,
   observacao_cd=nullif(trim(coalesce(p_observacao,'')),''),
   conferido_por=v_uid,conferido_at=now(),updated_at=now()
 WHERE id=v_p.id;
 INSERT INTO public.auditoria_eventos(empresa_id,usuario_id,entidade,entidade_id,acao,dados)
 VALUES(p_empresa_id,v_uid,'PRESTACAO',v_p.id::text,'PRESTACAO_CONFERIDA_CD_V108',
  jsonb_build_object('status',v_status,'divergencia_total',v_div,'taxa_cartao',p_taxa_cartao));
 RETURN jsonb_build_object('id',v_p.id,'status',v_status,'divergencia',v_div);
END;
$$;

