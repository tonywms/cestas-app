 CHECK (destino_recebimento_v108 IS NULL OR destino_recebimento_v108 IN ('EMPRESA','ENTREGADOR'));

CREATE OR REPLACE FUNCTION app_private.definir_destino_recebimento_v108()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path TO ''
AS $$
DECLARE v_pix text;v_cartao text;
BEGIN
  SELECT ec.destino_pix_v108,ec.destino_cartao_v108 INTO v_pix,v_cartao
    FROM public.empresa_configuracoes ec WHERE ec.empresa_id=NEW.empresa_id;
  IF NOT FOUND THEN RAISE EXCEPTION 'Configuração da empresa não encontrada.'; END IF;
  NEW.destino_recebimento_v108 := CASE
    WHEN NEW.forma_pagamento='DINHEIRO' THEN 'ENTREGADOR'
    WHEN NEW.forma_pagamento='PIX' THEN v_pix
    WHEN NEW.forma_pagamento='CARTAO' THEN v_cartao
    ELSE NULL END;
  RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS trg_recebimento_destino_v108 ON public.venda_recebimentos;
