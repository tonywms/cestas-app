 CHECK (destino_pix_v108 IN ('EMPRESA','ENTREGADOR'));
ALTER TABLE public.empresa_configuracoes
 DROP CONSTRAINT IF EXISTS configuracoes_destino_cartao_v108_ck;
ALTER TABLE public.empresa_configuracoes ADD CONSTRAINT configuracoes_destino_cartao_v108_ck
 CHECK (destino_cartao_v108 IN ('EMPRESA','ENTREGADOR'));
ALTER TABLE public.venda_recebimentos
 ADD COLUMN IF NOT EXISTS destino_recebimento_v108 text;
ALTER TABLE public.pagamentos
 ADD COLUMN IF NOT EXISTS destino_recebimento_v108 text;
