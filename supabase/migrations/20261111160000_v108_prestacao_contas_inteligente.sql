FOR EACH ROW EXECUTE FUNCTION app_private.definir_destino_recebimento_v108();
DROP TRIGGER IF EXISTS trg_pagamento_destino_v108 ON public.pagamentos;
CREATE TRIGGER trg_pagamento_destino_v108 BEFORE INSERT ON public.pagamentos
FOR EACH ROW EXECUTE FUNCTION app_private.definir_destino_recebimento_v108();

